/* ============================ sequence file I/O ============================ */
function parseFasta(text){
  const out=[]; let cur=null;
  text.split(/\r?\n/).forEach(l=>{
    if(l.startsWith(">")){ cur={name:l.slice(1).trim().split(/\s+/)[0]||"sequence", desc:l.slice(1).trim(), seq:"", features:[]}; out.push(cur); }
    else if(cur) cur.seq += l.replace(/[^A-Za-z]/g,"");
  });
  out.forEach(r=>{r.seq=clean(r.seq); r.topology="linear"; r.source="FASTA";});
  return out.filter(r=>r.seq.length);
}
function parseGenBank(text){
  const recs=[];
  text.split(/^\/\//m).forEach(chunk=>{
    if(!/LOCUS/.test(chunk)) return;
    const lines=chunk.split(/\r?\n/);
    const rec={name:"sequence",desc:"",seq:"",features:[],topology:"linear",source:"GenBank"};
    const loc=lines.find(l=>l.startsWith("LOCUS"));
    if(loc){
      const p=loc.trim().split(/\s+/);
      if(p[1]) rec.name=p[1];
      if(/circular/i.test(loc)) rec.topology="circular";
    }
    const def=lines.find(l=>l.startsWith("DEFINITION"));
    if(def) rec.desc=def.replace(/^DEFINITION\s*/,"").trim();
    let mode=null, cur=null;
    for(const raw of lines){
      if(/^FEATURES/.test(raw)){ mode="feat"; continue; }
      if(/^ORIGIN/.test(raw)){ if(cur) rec.features.push(cur); cur=null; mode="seq"; continue; }
      if(/^[A-Z]/.test(raw) && mode==="feat"){ if(cur){rec.features.push(cur);cur=null;} mode=null; continue; }
      if(mode==="feat"){
        const m=raw.match(/^ {5}(\S+)\s+(\S.*)$/);
        if(m){
          if(cur) rec.features.push(cur);
          const locs=m[2].trim();
          const comp=/complement/.test(locs);
          const nums=(locs.match(/\d+/g)||[]).map(Number);
          cur={type:m[1], label:"", start:nums.length?Math.min.apply(null,nums):1,
               end:nums.length?Math.max.apply(null,nums):1, strand:comp?-1:1, join:/join/.test(locs)};
        } else if(cur){
          const q=raw.trim();
          const lm=q.match(/^\/(label|gene|product|note|standard_name|locus_tag)="?([^"]*)"?/);
          if(lm && !cur.label) cur.label=lm[2];
          else if(q.startsWith("/") && /="?$/.test(q)===false && !cur.label){}
        }
      } else if(mode==="seq"){
        rec.seq += raw.replace(/[^A-Za-z]/g,"");
      }
    }
    if(cur) rec.features.push(cur);
    rec.seq=clean(rec.seq);
    rec.features=rec.features.filter(f=>f.end<=rec.seq.length+1 && !f.join)
      .map(f=>({type:f.type,label:f.label||f.type,start:f.start,end:f.end,strand:f.strand}));
    if(rec.seq.length) recs.push(rec);
  });
  return recs;
}
function parseSeqFile(name, text){
  if(/^\s*LOCUS/m.test(text)) return parseGenBank(text);
  if(/^\s*>/.test(text)) return parseFasta(text);
  const s=clean(text);
  if(s.length>20 && s.length >= text.replace(/\s/g,"").length*0.9)
    return [{name:name.replace(/\.[^.]+$/,""),desc:"",seq:s,features:[],topology:"linear",source:"raw"}];
  return [];
}
const MONTHS=["JAN","FEB","MAR","APR","MAY","JUN","JUL","AUG","SEP","OCT","NOV","DEC"];
function gbDate(){const d=new Date();return String(d.getDate()).padStart(2,"0")+"-"+MONTHS[d.getMonth()]+"-"+d.getFullYear();}
function toGenBank(rec){
  const n=rec.seq.length;
  let s="LOCUS       "+(rec.name||"construct").slice(0,24).padEnd(24," ")+String(n).padStart(7," ")+" bp    DNA     "+
        (rec.topology==="circular"?"circular":"linear  ")+" SYN "+gbDate()+"\n";
  s+="DEFINITION  "+(rec.desc||rec.name||"Gateway construct")+"\n";
  s+="ACCESSION   .\nVERSION     .\nKEYWORDS    .\nSOURCE      synthetic DNA construct\n";
  s+="  ORGANISM  synthetic DNA construct\n";
  s+="COMMENT     Generated by Gateway Bench.\n";
  s+="FEATURES             Location/Qualifiers\n";
  (rec.features||[]).forEach(f=>{
    const loc=(f.strand===-1?"complement("+f.start+".."+f.end+")":f.start+".."+f.end);
    s+="     "+String(f.type||"misc_feature").slice(0,15).padEnd(16," ")+loc+"\n";
    s+="                     /label=\""+String(f.label||"").replace(/"/g,"'")+"\"\n";
    if(f.note) s+="                     /note=\""+String(f.note).replace(/"/g,"'")+"\"\n";
  });
  s+="ORIGIN\n";
  const seq=rec.seq.toLowerCase();
  for(let i=0;i<seq.length;i+=60){
    let line=String(i+1).padStart(9," ");
    for(let j=0;j<60;j+=10){ const part=seq.slice(i+j,i+j+10); if(part) line+=" "+part; }
    s+=line+"\n";
  }
  return s+"//\n";
}
function toFastaText(name, seq){
  let s=">"+name+"\n";
  for(let i=0;i<seq.length;i+=70) s+=seq.slice(i,i+70)+"\n";
  return s;
}

