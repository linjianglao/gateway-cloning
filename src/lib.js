const CRC_T=(function(){const t=new Uint32Array(256);for(let n=0;n<256;n++){let c=n;
  for(let k=0;k<8;k++)c=c&1?0xEDB88320^(c>>>1):c>>>1;t[n]=c>>>0;}return t;})();
function crc32(u8){let c=0xFFFFFFFF;for(let i=0;i<u8.length;i++)c=CRC_T[(c^u8[i])&0xFF]^(c>>>8);return (c^0xFFFFFFFF)>>>0;}
function zipStore(files){ // files: [{name, text}]
  const enc=new TextEncoder(); const chunks=[]; const central=[]; let offset=0;
  const u16=v=>[v&255,(v>>8)&255], u32=v=>[v&255,(v>>8)&255,(v>>16)&255,(v>>>24)&255];
  const now=new Date();
  const dosTime=((now.getHours()<<11)|(now.getMinutes()<<5)|(now.getSeconds()>>1))&0xFFFF;
  const dosDate=(((now.getFullYear()-1980)<<9)|((now.getMonth()+1)<<5)|now.getDate())&0xFFFF;
  files.forEach(f=>{
    const nameB=enc.encode(f.name), dataB=enc.encode(f.text), crc=crc32(dataB);
    const local=[].concat(u32(0x04034b50),u16(20),u16(0),u16(0),u16(dosTime),u16(dosDate),
      u32(crc),u32(dataB.length),u32(dataB.length),u16(nameB.length),u16(0));
    chunks.push(new Uint8Array(local), nameB, dataB);
    central.push({nameB,crc,size:dataB.length,offset});
    offset += local.length + nameB.length + dataB.length;
  });
  const cdStart=offset; let cdLen=0;
  central.forEach(c=>{
    const h=[].concat(u32(0x02014b50),u16(20),u16(20),u16(0),u16(0),u16(dosTime),u16(dosDate),
      u32(c.crc),u32(c.size),u32(c.size),u16(c.nameB.length),u16(0),u16(0),u16(0),u16(0),u32(0),u32(c.offset));
    chunks.push(new Uint8Array(h), c.nameB);
    cdLen += h.length + c.nameB.length;
  });
  chunks.push(new Uint8Array([].concat(u32(0x06054b50),u16(0),u16(0),u16(central.length),u16(central.length),
    u32(cdLen),u32(cdStart),u16(0))));
  return new Blob(chunks,{type:"application/zip"});
}
